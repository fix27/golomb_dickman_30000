def arb_ceil_int(x):
    """целое >= x (для шара x)"""
    return int(x.upper().floor().upper().unique_fmpz()) + 1

def to_fixed(x, S):
    """шар x -> целые (L, H) с  x ⊂ [L*2^-S, H*2^-S]  (строго; округление наружу)"""
    old = ctx.prec
    ctx.prec = max(old, S + 128)
    sc = arb(1 << S)
    L = int((x.lower() * sc).floor().lower().unique_fmpz())
    H = int((x.upper() * sc).floor().upper().unique_fmpz()) + 1
    ctx.prec = old
    return L, H

def strip_constants(prec=384):
    """Лемма 4: M >= sup_{|y|<=d} ∫|G(x+iy)|dx  при d = 7/5 (явные оценки трёх областей)."""
    ctx.prec = prec
    one = arb(1); pi = arb.pi(); gam = arb.const_euler(); e = one.exp()
    d = arb(7) / 5
    c = d.cos();  assert c > 0
    a = 2 * c
    # область t <= 0:  |u|<=1,  |F|<=C1|u|
    C1 = (gam + 2 + (e - 2) / 2).exp()
    M1 = C1 * (-a).exp() * (2 / a + 1 / (a * a))
    # область 0 <= t <= 2:  |u| <= e^2
    e2 = arb(2).exp(); em2 = (-arb(2)).exp()
    B2 = 2 * gam.exp() * (e2 * e2) * (2 * e2 + e2.exp() / 2).exp()
    M2 = 2 * B2
    # область t >= 2:  |arg u| <= theta_max < pi/2,  Re u >= kappa |u|
    th = d + em2 * d.sin();  assert th < pi / 2
    kap = th.cos();          assert kap > 0
    kp = kap * (-em2).exp()
    facE = ((em2 - 2).exp()).exp()          # exp(1/rho_min(2)) >= exp(|E1|)
    M3 = facE * (1 + em2) * (-kp * e2).exp() / kp
    return dict(d=d, M=M1 + M2 + M3, M1=M1, M2=M2, M3=M3, pi=pi, gam=gam)

def solve_t(target_lnu, lo, hi):
    """double: t с  t - e^{-t} = target_lnu  (монотонная функция)"""
    for _ in range(200):
        m = 0.5 * (lo + hi)
        if m - math.exp(-m) < target_lnu: lo = m
        else: hi = m
    return 0.5 * (lo + hi)

def make_plan(D, G=30):
    N = D + G
    K = strip_constants(); ctx.prec = 384
    M, d, pi, gam = K["M"], K["d"], K["pi"], K["gam"]
    ten = arb(10)
    # --- шаг h: из требования  2M/(e^{2 pi d/h}-1) < 10^-(N+6)
    L = (2 * M).log() + (N + 6) * ten.log()
    Lint = arb_ceil_int(L)
    h = math.floor(0.97 * 2 * math.pi * 1.4 / Lint * 2**40) / 2**40         # двоично-рациональный double
    hA = arb(h)
    Bdisc = 2 * M / ((2 * pi * d / hA).exp() - 1)
    assert Bdisc * ten**(N + 6) < 1, "оценка дискретизации не достигнута"
    # --- хвосты суммы
    UR = int(math.ceil((N + 8) * LN10)) + 2                                    # e^-UR < 10^-(N+8)
    tR = solve_t(math.log(UR), 0.0, 40.0);  K_R = int(math.ceil(tR / h)) + 1
    t = arb(K_R) * hA;  uR = (t - (-t).exp()).exp()
    assert uR >= UR and uR >= 1, "правый хвост"
    tailR = (-uR).exp()                                                        # Лемма 3: Σ_{k>K_R} h G <= e^{-u_R}
    lnuL = 0.5 * (-(N + 8) * LN10 + LN2 - EULER_F) - 1.0                       # e^g u_L^2/2 < 10^-(N+8)
    tL = solve_t(lnuL, -600.0, 0.0);  K_L = int(math.ceil(-tL / h)) + 1
    t = -(arb(K_L) * hA);  uL = (t - (-t).exp()).exp()
    tailL = gam.exp() * uL * uL / 2                                            # Лемма 3: Σ_{k<-K_L} h G <= e^g u_L^2/2
    assert tailL * ten**(N + 8) < 1, "левый хвост"
    Ebits = int(math.ceil((N + 8) * LOG2_10)) + 6                              # допуск на узел: eps = 2^-Ebits
    S = Ebits + 64                                                             # масштаб целочисленной арифметики
    pl = dict(D=D, G=G, N=N, h=h, K_L=K_L, K_R=K_R, Ebits=Ebits, S=S, EGbits=int(Ebits * 1.45) + 700, M=M, Bdisc=Bdisc, tailR=tailR, tailL=tailL,
              consts=K, nodes=K_L + K_R + 1)
    return pl

