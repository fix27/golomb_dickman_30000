"""## §3. Константы, шаг $h$, хвосты и границы ошибок
`make_plan` вычисляет в шарах Arb: $M$ (Лемма 4), шаг $h$ (двоично-рациональный `double`, точное число) из условия $B_{\rm disc}<10^{-(D+G+6)}$, индексы $K_L,K_R$ и величины $\tau_L,\tau_R<10^{-(D+G+8)}$; все неравенства **проверяются** утверждениями `assert` в шарах. `to_fixed` переводит шар в пару целых $[L,H]$ (единица $2^{-S}$) с округлением наружу.
"""

def arb_ceil_int(x):
    """целое >= x (для шара x)"""
    return int(x.upper().floor().upper().unique_fmpz()) + 1

def to_fixed(x, S):
    """шар x -> целые (L, H) с  x ⊂ [L*2^-S, H*2^-S]  (строго; округление наружу)"""
    old = ctx.prec
    ctx.prec = max(old, S + 128)
    sc = arb(1 << S)
    L = int((x.lower() * sc).floor().lower().unique_fmpz())
    H = int((x.upper() * sc).floor().upper().unique_fmpz()) + 1
    ctx.prec = old
    return L, H

def strip_constants(prec=384):
    """Лемма 4: M >= sup_{|y|<=d} ∫|G(x+iy)|dx  при d = 7/5 (явные оценки трёх областей)."""
    ctx.prec = prec
    one = arb(1); pi = arb.pi(); gam = arb.const_euler(); e = one.exp()
    d = arb(7) / 5
    c = d.cos();  assert c > 0
    a = 2 * c
    # область t <= 0:  |u|<=1,  |F|<=C1|u|
    C1 = (gam + 2 + (e - 2) / 2).exp()
    M1 = C1 * (-a).exp() * (2 / a + 1 / (a * a))
    # область 0 <= t <= 2:  |u| <= e^2
    e2 = arb(2).exp(); em2 = (-arb(2)).exp()
    B2 = 2 * gam.exp() * (e2 * e2) * (2 * e2 + e2.exp() / 2).exp()
    M2 = 2 * B2
    # область t >= 2:  |arg u| <= theta_max < pi/2,  Re u >= kappa |u|
    th = d + em2 * d.sin();  assert th < pi / 2
    kap = th.cos();          assert kap > 0
    kp = kap * (-em2).exp()
    facE = ((em2 - 2).exp()).exp()          # exp(1/rho_min(2)) >= exp(|E1|)
    M3 = facE * (1 + em2) * (-kp * e2).exp() / kp
    return dict(d=d, M=M1 + M2 + M3, M1=M1, M2=M2, M3=M3, pi=pi, gam=gam)

def solve_t(target_lnu, lo, hi):
    """double: t с  t - e^{-t} = target_lnu  (монотонная функция)"""
    for _ in range(200):
        m = 0.5 * (lo + hi)
        if m - math.exp(-m) < target_lnu: lo = m
        else: hi = m
    return 0.5 * (lo + hi)

def make_plan(D, G=30):
    N = D + G
    K = strip_constants(); ctx.prec = 384
    M, d, pi, gam = K["M"], K["d"], K["pi"], K["gam"]
    ten = arb(10)
    # --- шаг h: из требования  2M/(e^{2 pi d/h}-1) < 10^-(N+6)
    L = (2 * M).log() + (N + 6) * ten.log()
    Lint = arb_ceil_int(L)
    h = math.floor(0.97 * 2 * math.pi * 1.4 / Lint * 2**40) / 2**40         # двоично-рациональный double
    hA = arb(h)
    Bdisc = 2 * M / ((2 * pi * d / hA).exp() - 1)
    assert Bdisc * ten**(N + 6) < 1, "оценка дискретизации не достигнута"
    # --- хвосты суммы
    UR = int(math.ceil((N + 8) * LN10)) + 2                                    # e^-UR < 10^-(N+8)
    tR = solve_t(math.log(UR), 0.0, 40.0);  K_R = int(math.ceil(tR / h)) + 1
    t = arb(K_R) * hA;  uR = (t - (-t).exp()).exp()
    assert uR >= UR and uR >= 1, "правый хвост"
    tailR = (-uR).exp()                                                        # Лемма 3: Σ_{k>K_R} h G <= e^{-u_R}
    lnuL = 0.5 * (-(N + 8) * LN10 + LN2 - EULER_F) - 1.0                       # e^g u_L^2/2 < 10^-(N+8)
    tL = solve_t(lnuL, -600.0, 0.0);  K_L = int(math.ceil(-tL / h)) + 1
    t = -(arb(K_L) * hA);  uL = (t - (-t).exp()).exp()
    tailL = gam.exp() * uL * uL / 2                                            # Лемма 3: Σ_{k<-K_L} h G <= e^g u_L^2/2
    assert tailL * ten**(N + 8) < 1, "левый хвост"
    Ebits = int(math.ceil((N + 8) * LOG2_10)) + 6                              # допуск на узел: eps = 2^-Ebits
    S = Ebits + 64                                                             # масштаб целочисленной арифметики
    pl = dict(D=D, G=G, N=N, h=h, K_L=K_L, K_R=K_R, Ebits=Ebits, S=S, EGbits=int(Ebits * 1.45) + 700, M=M, Bdisc=Bdisc, tailR=tailR, tailL=tailL,
              consts=K, nodes=K_L + K_R + 1)
    return pl

def log10_arb(x):
    """целая часть log10(x) (для печати)"""
    ctx.prec = 384
    return int((x.upper().log() / arb(10).log()).floor().lower().unique_fmpz())

"""## §4. Строгие шары для узлов $G(kh)$ (Лемма 6, 7)

**Откуда берётся скорость (и почему строгость не страдает).** Основная работа — узлы $1\lesssim u\lesssim\mathrm{tol}/3$: ряд требует $\approx6.5\,u$ членов, а каждый член — полное умножение на $u$ при ~$10^5$ бит; в сумме это порядка $10^9$ полных умножений. Поэтому:
1. *прямоугольное расщепление* ряда: в ~2.5 раза меньше полных умножений (проверено подсчётом операций);
2. *цепная дробь Стилтьеса* для больших $u$: число уровней падает с $\sim6.5u$ до $\sim\mathrm{X}\,(0.2+0.14\,\mathrm{X}/u)$, где $X=\ln(1/\text{допуск})-2u$, и считается она при меньшей точности;
3. *автотюн*: порог $u_{\rm cf}$, с которого цепная дробь быстрее ряда, определяется замером на этой машине при реальной точности (можно задать вручную).

**Выбор метода не влияет на строгость:** все три формулы верны для любого $u>0$, а радиус каждого узла проверяется (`rad < eps`) независимо от метода. Если метод не уложился, точность поднимается, а узел пересчитывается.
"""

ASYM_KMAX = 3000
RS_M = 8                        # размер блока прямоугольного расщепления
_EGC = {"bits": 0, "val": None}

def get_EG(bits):
    """e^gamma с точностью >= bits бит (кэш на процесс)"""
    if _EGC["val"] is None or _EGC["bits"] < bits:
        old = ctx.prec
        b = int(bits * 1.2) + 256
        ctx.prec = b
        _EGC["val"], _EGC["bits"] = arb.const_euler().exp(), b
        ctx.prec = old
    return _EGC["val"]

# ---------------------------------------------------------------- ряд (Лемма 1a, 1d)
def series_S_naive(u, uf, thr):
    """S = sum_{k=2}^K (-u)^k/(k k!) и rem: |sum_{k>K}| <= rem < thr (строго); K+1 >= 2u => хвост <= 2|a_{K+1}|.
       (эталонная медленная реализация: одно полное умножение на член)"""
    ub = u.upper()
    kmin = max(3, int(2 * uf * 1.01) + 6)
    while not (arb(kmin) >= 2 * ub):
        kmin += 8
    mu = -u
    p = mu
    S = arb(0)
    k = 1
    while True:
        k += 1
        p = p * mu / k
        S = S + p / k
        if k >= kmin and (k < 64 or k % 16 == 0):
            rem = 2 * abs(p).upper() * ub / ((k + 1) * (k + 1))
            if rem < thr:
                return S, rem

def _ln_a(k, xf):
    return k * xf - math.lgamma(k + 1.0) - math.log(k)

def _K_target(uf, xf, thr_bits):
    """(double) наименьшее K, при котором 2|a_{K+1}| < 2^-thr_bits и K+1 >= 2u; лишь для выбора числа блоков"""
    lim = -(thr_bits + 3) * LN2
    lo = max(3, int(2 * uf * 1.02) + 8)
    hi = lo
    while _ln_a(hi + 1, xf) > lim:
        hi = hi * 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if _ln_a(mid + 1, xf) > lim: lo = mid
        else: hi = mid
    return hi

def series_S(u, uf, xf, thr_bits, m=None):
    """То же S и rem, но прямоугольным расщеплением: блок из m членов считается через степени x^j (j<=m) и
       МАЛЫЕ целые коэффициенты, на блок остаётся 2 полных умножения вместо m. Это точная перестановка
       конечной суммы S_K (в шарах), остаток - Лемма 1(d) по |a_{K+1}|, который получается бесплатно как
       префактор следующего блока."""
    m = m or RS_M
    thr = arb(1) / arb(1 << thr_bits)
    ub = u.upper()
    K = _K_target(uf, xf, thr_bits)
    if K < 4 * m:
        return series_S_naive(u, uf, thr)
    while True:
        nblocks = (K - 1 + m - 1) // m
        Kend = 1 + nblocks * m                                  # последний учтённый индекс
        if not (arb(Kend + 1) >= 2 * ub):                       # условие леммы 1(d): K+1 >= 2u
            K = int(K * 1.1) + 16
            continue
        x = -u
        xp = [arb(1), x]
        for j in range(2, m + 1):
            xp.append(xp[-1] * x)
        xm = xp[m]
        kb = 2
        pref = xp[2] / 4                                        # a_2 = x^2/(2*2!)
        S = arb(0)
        for _ in range(nblocks):
            inner = arb(1)                                      # j = 0: отношение 1
            Dprod = 1
            for j in range(1, m):                               # a_{kb+j}/a_{kb} = x^j * kb / ((kb+j) prod_{i=1..j}(kb+i))
                Dprod *= (kb + j)
                inner = inner + (xp[j] * kb) / ((kb + j) * Dprod)
            S = S + pref * inner
            Dprod *= (kb + m)
            pref = (pref * xm) * kb / ((kb + m) * Dprod)        # a_{kb+m}
            kb += m
        rem = 2 * abs(pref).upper()                             # pref = a_{Kend+1}
        if rem < thr:
            return S, rem
        K = int(K * 1.1) + 16                                   # (редко) не хватило - добавляем блоки

# ---------------------------------------------------------------- цепная дробь Стилтьеса (Лемма 7)
class _Escalate(Exception):
    pass

def cf_f_hull(u, uf, gap_bits, nmax):
    """Шар для f = e^u E1(u), u>0:  f = B_n/A_n  (подходящие дроби цепной дроби 1/(z+1/(1+1/(z+2/(1+2/(z+...)))))).
       По теореме Стилтьеса f лежит между f_{n-1} и f_n, поэтому |f - f_n| <= |f_n - f_{n-1}|."""
    thr = arb(1) / arb(1 << gap_bits)
    A2, A1 = arb(1), u                 # A_{-1}, A_0
    B2, B1 = arb(0), arb(1)
    n = 0
    while n < nmax:
        for _ in range(32):
            n += 1
            a = (n + 1) // 2
            if n & 1:                  # b_n = 1: только малые множители
                A2, A1 = A1, A1 + a * A2
                B2, B1 = B1, B1 + a * B2
            else:                      # b_n = u: одно полное умножение на последовательность
                A2, A1 = A1, u * A1 + a * A2
                B2, B1 = B1, u * B1 + a * B2
        fn = B1 / A1
        D = abs(fn - B2 / A2).upper()
        if D < thr:
            return fn + arb(0, D)
    raise _Escalate("цепная дробь: превышен nmax")

# ---------------------------------------------------------------- асимптотика (Лемма 1c)
def asym_K(xf, uf, lng, L_eps):
    """минимальное K (double - только выбор метода), при котором остаток асимптотического ряда достаточно мал"""
    top = min(ASYM_KMAX, int(uf) - 1)
    lnfact = 0.0
    for K in range(0, top + 1):
        if K > 0:
            lnfact += math.log(K)
        if lng + lnfact - (K + 1) * xf - uf <= -L_eps - 3.0:
            return K
    return None

def _mk_u(k, pl):
    t = arb(pl["h"]) * k
    em = (-t).exp()
    return em, (t - em).exp()

def _eval_series(k, pl, P, thr_bits, uf, xf):
    Pv = P + (int(uf / LN2) + 16 if uf > 1 else 0)          # запас на сокращение членов (~e^u)
    ctx.prec = Pv
    em, u = _mk_u(k, pl)
    S, rem = series_S(u, uf, xf, thr_bits)
    expo = -2 * u + S + arb(0, rem)                         # F = e^g u exp(-2u + S)        (Лемма 1a)
    return get_EG(Pv) * u * u * (1 + em) * expo.exp()       # G = F u (1 + e^-t)

def _eval_cf(k, pl, P, gap_bits, uf, nmax):
    ctx.prec = P
    em, u = _mk_u(k, pl)
    ctx.prec = gap_bits + 96 + int(math.log2(nmax + 2))     # f нужна с ОТНОСИТЕЛЬНОЙ точностью ~2^-gap_bits (дешевле, чем P)
    f = cf_f_hull(u, uf, gap_bits, nmax)
    ctx.prec = P
    E1 = (-u).exp() * f                                      # E1 = e^-u f
    return (-u - E1).exp() * u * (1 + em)

def _eval_asym(k, pl, P, K):
    ctx.prec = P
    em, u = _mk_u(k, pl)
    w = (-u).exp()
    if K == 0:
        Ssum = arb(0)
    else:
        Ssum = arb(1)
        for j in range(K - 1, 0, -1):                       # Горнер: sum_{j<K} (-1)^j j!/u^j
            Ssum = 1 - Ssum * j / u
    f = arb(1)
    for j in range(1, K + 1):
        f = f * j / u
    rem = f / u                                              # K!/u^(K+1)       (Лемма 1c, остаток)
    E1 = w * (Ssum / u + arb(0, rem))                        # E1(u) = e^-u (S/u + R),  |R| <= K!/u^(K+1)
    return (-u - E1).exp() * u * (1 + em)

def _est(k, pl):
    h = pl["h"]
    tf = k * h
    emf = math.exp(-tf); xf = tf - emf
    uf = math.exp(xf) if xf < 700.0 else math.inf
    l1p = math.log1p(emf)
    lng = (EULER_F + 2 * xf + l1p) if xf < 0 else (xf - uf + l1p)     # ln(верхней оценки G)
    return xf, uf, lng

def method_of(k, pl):
    """(только для статистики/автотюна) какой метод выберет node_ball"""
    xf, uf, lng = _est(k, pl)
    L_eps = pl["Ebits"] * LN2
    if L_eps + lng + 2.0 < 0: return "skip"
    if xf >= 0 and asym_K(xf, uf, lng, L_eps) is not None: return "asym"
    if xf >= 0 and uf >= pl.get("cf_min_u", 1e18): return "cf"
    return "series"

def node_ball(k, pl, force=None):
    """строгий шар для G(kh) = F(u) u (1+e^-t), u = exp(t - e^-t), t = kh; радиус < eps = 2^-Ebits"""
    Eb = pl["Ebits"]
    xf, uf, lng = _est(k, pl)
    L_eps = Eb * LN2
    eps = arb(1) / arb(1 << Eb)
    need_ln = L_eps + lng + 2.0
    if need_ln < 0:                                                   # узел < eps: шар [0, оценка]
        ctx.prec = 128
        em, u = _mk_u(k, pl)
        g = (get_EG(128) * u * u * (1 + em)) if xf < 0 else (u * (-u).exp() * (1 + em))
        ub = g.upper()
        return ub / 2 + arb(0, ub / 2)                                # шар [0, ub]
    P = max(64, int(need_ln / LN2) + int(math.log2(uf + 2.0)) + 64)
    thr_bits = int(need_ln / LN2) + 4
    gap_bits = max(32, int((L_eps + lng - uf + 4.0) / LN2) + 2) if xf >= 0 else 0
    meth = force or method_of(k, pl)
    Ka = asym_K(xf, uf, lng, L_eps) if (xf >= 0 and meth == "asym") else None
    X = max(L_eps + lng - uf + xf, 1.0) if xf >= 0 else 1.0           # нужная точность f, нат (оценка числа уровней)
    nmax = int(3.0 * X * (0.22 + 0.14 * X / max(uf, 1.0))) + 4000
    for attempt in range(8):
        try:
            if meth == "asym" and Ka is not None:
                g = _eval_asym(k, pl, P, Ka)
            elif meth == "cf":
                g = _eval_cf(k, pl, P, gap_bits, uf, nmax)
            else:
                g = _eval_series(k, pl, P, thr_bits, uf, xf)
            if g.is_finite() and g.rad() < eps:
                return g
        except _Escalate:
            nmax *= 2
        P += max(64, P // 4); thr_bits += max(64, thr_bits // 4); gap_bits += max(32, gap_bits // 4)
    raise ArithmeticError("узел k=%d: радиус не достигнут" % k)

def autotune_cf_min_u(pl, log=print):
    """Подбор порога u, с которого цепная дробь быстрее ряда (на ЭТОЙ машине и при ЭТОЙ точности).
       Корректность не зависит от порога: оба метода строгие."""
    L_eps = pl["Ebits"] * LN2
    cand = None
    for uu in (20000, 16000, 13000, 10000, 8000, 6000, 4500, 3000):
        if uu > 0.30 * L_eps:                      # выше - работает асимптотика / нет таких узлов
            continue
        t = solve_t(math.log(uu), 0.0, 40.0)
        k = int(round(t / pl["h"]))
        res = {}
        for name in ("cf", "series"):
            t0 = time.time()
            node_ball(k, pl, force=name)
            res[name] = time.time() - t0
        log("  автотюн u~%6d: ряд %.2f с | цепная дробь %.2f с" % (uu, res["series"], res["cf"]))
        if res["cf"] < 0.9 * res["series"]: cand = uu
        else: break
    return float(cand) if cand is not None else 1e18

"""## §5. Параллельный расчёт с чекпоинтами
Куски узлов считаются в процессах; результат куска — пара целых $[L,H]$ (строгое включение суммы шаров), поэтому через границы процессов ничего не теряется. Чекпоинты (`pickle`) позволяют продолжить после обрыва сессии.
"""

def run_chunk(lo, hi, pl):
    S = pl["S"]
    get_EG(pl["EGbits"])                       # e^gamma один раз на процесс, с запасом точности
    ctx.prec = pl["Ebits"] + 256
    se, so = arb(0), arb(0)
    for k in range(lo, hi):
        g = node_ball(k, pl)
        ctx.prec = pl["Ebits"] + 256
        if k & 1: so = so + g
        else:     se = se + g
    return lo, hi, to_fixed(se, S), to_fixed(so, S)

def compute_chunks(pl, jobs, chunk, ckpt, deadline=None, log=print):
    pw = {k: pl[k] for k in ("D", "G", "h", "Ebits", "S", "EGbits", "K_L", "K_R", "cf_min_u")}   # в процессы передаём только числа
    n0, n1 = -pl["K_L"], pl["K_R"] + 1
    bounds = [(lo, min(lo + chunk, n1)) for lo in range(n0, n1, chunk)]
    meta = (pl["D"], pl["G"], pl["h"], pl["Ebits"], pl["K_L"], pl["K_R"], chunk, "v2")
    done = {}
    if ckpt:
        os.makedirs(ckpt, exist_ok=True)
        mp = os.path.join(ckpt, "meta.pkl")
        if os.path.exists(mp):
            with open(mp, "rb") as f:
                if pickle.load(f) != meta:
                    raise RuntimeError(ckpt + ": чекпоинты другого прогона - удалите папку или смените ckpt")
        else:
            with open(mp, "wb") as f: pickle.dump(meta, f)
        for lo, hi in bounds:
            p = os.path.join(ckpt, "c_%d.pkl" % lo)
            if os.path.exists(p):
                try:
                    with open(p, "rb") as f: c = pickle.load(f)
                    if c[0] == lo and c[1] == hi: done[lo] = c
                except Exception:
                    pass
    todo = sorted([b for b in bounds if b[0] not in done], key=lambda b: -b[0])      # дорогие (большие u) - первыми
    if done: log("  из чекпоинта: %d/%d кусков" % (len(done), len(bounds)))
    t0 = time.time(); fin = 0
    def accept(c):
        nonlocal fin
        done[c[0]] = c
        if ckpt:
            p = os.path.join(ckpt, "c_%d.pkl" % c[0])
            with open(p + ".tmp", "wb") as f: pickle.dump(c, f)
            os.replace(p + ".tmp", p)
        fin += 1
        el = time.time() - t0
        print("\r  куски %d/%d  прошло %6.0fс  осталось ~%6.0fс   " % (len(done), len(bounds), el, el / fin * (len(todo) - fin)),
              end="", flush=True)
    stopped = False
    if jobs <= 1 or len(todo) <= 1:
        for lo, hi in todo:
            if deadline and time.time() > deadline: stopped = True; break
            accept(run_chunk(lo, hi, pw))
    else:
        with ProcessPoolExecutor(max_workers=jobs, mp_context=_get_mp_context()) as ex:
            pending = {ex.submit(run_chunk, lo, hi, pw) for lo, hi in todo}
            while pending:
                tmo = None if not deadline else max(1.0, min(30.0, deadline - time.time()))
                fin_set, pending = wait(pending, timeout=tmo, return_when=FIRST_COMPLETED)
                for f in fin_set: accept(f.result())
                if deadline and time.time() > deadline and pending:
                    stopped = True
                    for f in pending: f.cancel()
                    for f in [f for f in pending if not f.cancelled()]: accept(f.result())
                    pending = set()
    if todo: print()
    if stopped: return None
    return [done[k] for k in sorted(done)]

"""## §6. Итоговый сертификат
Всё в точной целочисленной арифметике Python: $\Lambda_-=\lfloor hL\rfloor-B$, $\Lambda_+=\lceil hH\rceil+\tau_R+\tau_L+B$ (в единицах $2^{-S}$), затем $\lfloor10^D\Lambda_\pm 2^{-S}\rfloor$.
"""

def certify(pl, chunks, verbose=True):
    """Итоговый строгий интервал для lambda в целых числах (единица = 2^-S) и сертификат цифр."""
    S, D = pl["S"], pl["D"]
    hn, hd = pl["h"].as_integer_ratio()                       # h = hn/hd точно (hd - степень двойки)
    Lsum = sum(c[2][0] + c[3][0] for c in chunks)
    Hsum = sum(c[2][1] + c[3][1] for c in chunks)
    lo_fin = (hn * Lsum) // hd                                # пол
    hi_fin = -((-hn * Hsum) // hd)                            # потолок
    B = to_fixed(pl["Bdisc"], S)[1]                           # |ошибка дискретизации| <= B (Лемма 5)
    TR = to_fixed(pl["tailR"], S)[1]; TL = to_fixed(pl["tailL"], S)[1]     # хвосты >= 0 (Лемма 3)
    lam_lo = lo_fin - B
    lam_hi = hi_fin + TR + TL + B
    assert lam_lo > 0 and lam_hi > lam_lo
    scale = 10 ** D
    a = (lam_lo * scale) >> S; b = (lam_hi * scale) >> S
    res = dict(lam_lo=lam_lo, lam_hi=lam_hi, S=S, proven=(a == b), digits=(str(a).zfill(D) if a == b else None),
               digits_lo=str(a).zfill(D), digits_hi=str(b).zfill(D))
    if verbose:
        w = lam_hi - lam_lo
        print("ширина строгого интервала ~ 2^-%d ≈ 10^-%.1f" % (S - w.bit_length(), (S - w.bit_length()) * math.log10(2)))
        print("оценка дискретизации B ≈ 10^%d,  хвосты ≈ 10^%d / 10^%d" % (log10_arb(pl["Bdisc"]), log10_arb(pl["tailR"]), log10_arb(pl["tailL"])))
        print("ВСЕ %d ЗНАКОВ ДОКАЗАНЫ (floor(lo*10^D) == floor(hi*10^D))" % D if res["proven"] else
              "ЗНАКИ НЕ ДОКАЗАНЫ: нижняя и верхняя границы различаются - увеличьте GUARD")
    return res

