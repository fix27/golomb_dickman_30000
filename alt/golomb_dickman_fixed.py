def run_certificate(D, G=30, jobs=0, chunk=0, ckpt=None, out=None, max_hours=0.0,
                    cf_min_u=None, trust_checkpoint=False):
    """ckpt=None  - путь по умолчанию в папке скрипта;
       ckpt=""    - без чекпоинтов;
       ckpt=path  - использовать указанный (абсолютный или относительный) путь."""
    t0 = time.time()
    try: ncpu = len(os.sched_getaffinity(0))
    except AttributeError: ncpu = os.cpu_count() or 1
    jobs = jobs if jobs > 0 else (min(ncpu, 4) if os.path.isdir("/kaggle/working") else ncpu)
    # Абсолютный путь: папка рядом со скриптом, а не относительно текущего CWD.
    try:
        _SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
    except NameError:
        _SCRIPT_DIR = os.path.abspath(os.getcwd())
    base = "/kaggle/working" if os.path.isdir("/kaggle/working") else _SCRIPT_DIR
    if ckpt is None:
        ckpt = os.path.join(base, "gd_rigorous_ckpt_%d" % D)
    # ckpt == "" - это осознанное «без чекпоинтов», оставляем как есть.
    pl = make_plan(D, G)
    print("D=%d  GUARD=%d  узлов=%d  h=%.6e  K_L=%d K_R=%d  процессов=%d" % (D, G, pl["nodes"], pl["h"], pl["K_L"], pl["K_R"], jobs))
    print("  M ≈ 10^%d,  B_disc ≈ 10^%d" % (log10_arb(pl["M"]), log10_arb(pl["Bdisc"])))
    if cf_min_u is None:
        cf_min_u = autotune_cf_min_u(pl)
    pl["cf_min_u"] = float(cf_min_u)
    print("  порог цепной дроби: u >= %s" % ("∞ (только ряд)" if cf_min_u > 1e17 else "%.0f" % cf_min_u))
    if chunk <= 0: chunk = max(25, min(200, pl["nodes"] // (max(1, jobs) * 24)))
    deadline = time.time() + max_hours * 3600.0 if max_hours > 0 else None
    chunks = compute_chunks(pl, jobs, chunk, ckpt, deadline,
                            trust_checkpoint=trust_checkpoint)
    if chunks is None:
        print("ОСТАНОВЛЕНО по max_hours: чекпоинты в", ckpt, "- запустите ячейку снова"); return None
    res = certify(pl, chunks)
    k = min(D, 95)
    ok_known = res["digits_lo"][:k] == KNOWN[:k]
    print("независимая сверка с OEIS A084945 (первые %d знаков): %s" % (k, "OK" if ok_known else "НЕ СОВПАЛО"))
    if res["proven"] and ok_known:
        path = out if out is not None else os.path.join(base, "golomb_dickman_%d_certified.txt" % D)
        with open(path, "w") as f:
            f.write("# Golomb-Dickman constant, %d decimals, CERTIFIED by interval arithmetic (trapezoid rule + Arb balls)\n" % D)
            f.write("# S=%d lam_lo=%d\n# lam_hi=%d\n" % (res["S"], res["lam_lo"], res["lam_hi"]))
            f.write("0." + res["digits"] + "\n")
        print("записано", path, "| время %.0f с" % (time.time() - t0))
    return res

